#!/usr/bin/env python
"""
The "robots not moved" rule: FPS-era APOGEE exposures whose header records a
newly loaded configuration B while the fiber positioners were still at the
configuration A they were last moved to.

See README.md in this directory for the rule, its inputs and its exclusions.
Standard library only. Three steps:

``state``
    From the jaeger actor log lines (operations-software "tron" logs, kept at
    Utah) and the exposure start times, compute the robot state at the start
    of every FPS object exposure and keep those where the rule fires.
``cfgdiff``
    For those exposures, compare the APOGEE fiber -> catalogid assignments of
    the confSummary files of B and A (sdsscore). Adds the 0.4.0 release class
    and the fiber-level data-check verdict when those tables are given.
    Output: the candidate table (``robots_not_moved_candidates.csv``, shipped
    next to this script).
``overrides``
    From the candidate table, apply the selection and exclusions and write
    (a) the list CSV and (b) the generated block of
    ``src/almanac/etc/exposure_overrides.yaml`` (between the BEGIN/END
    markers), one ``not_science`` entry per observatory / MJD / (A, B) pair.

Only the last step is needed to regenerate the override entries; it reads the
shipped candidate table and nothing else.
"""

import argparse
import collections
import csv
import datetime as dt
import json
import os
import re
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
CANDIDATES = HERE / "robots_not_moved_candidates.csv"
OVERRIDES_YAML = REPO / "src" / "almanac" / "etc" / "exposure_overrides.yaml"
BEGIN = "  # BEGIN robots-not-moved (generated by scripts/robots_not_moved/robots_not_moved.py overrides; do not edit by hand)"
END = "  # END robots-not-moved"

#: A load older than this before the exposure start is not attributed to it.
MAX_LOAD_AGE_S = 3600
#: LCO before this MJD: header and log clocks disagree (robot trajectories
#: appear in the middle of normal exposures), so the signature is unreliable.
LCO_FIRST_RELIABLE_MJD = 60000

# --------------------------------------------------------------------------
# step 1: robot state from jaeger log lines
# --------------------------------------------------------------------------

_TS = re.compile(r"^(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)[,.]\d+Z?\s+(.*)$")


def read_jaeger_extract(paths):
    """
    Read jaeger log lines grouped per night.

    The input is the text written by ``remote_extract_jaeger.sh``: a header
    line ``#### <obs> <mjd> <actor> <log file name>`` followed by the matching
    log lines of that file. Only ``jaeger`` sections are used.

    Returns ``{(obs, mjd): [(datetime, line, log_file_name), ...]}`` sorted by time.
    """
    data = collections.defaultdict(list)
    for path in paths:
        key = None
        with open(path, encoding="utf-8", errors="replace") as fp:
            for line in fp:
                if line.startswith("#### "):
                    _, obs, mjd, actor, name = line.rstrip("\n").split(" ", 4)
                    key = (obs, int(mjd), name) if actor == "jaeger" else None
                    continue
                if key is None:
                    continue
                m = _TS.match(line)
                if m:
                    t = dt.datetime.strptime(m.group(1), "%Y-%m-%d %H:%M:%S")
                    data[key[:2]].append((t, m.group(2).rstrip(), key[2]))
    for k in data:
        data[k].sort(key=lambda x: x[0])
    return data


def _load_fields(line):
    """configuration_loaded=<config>,<design>,<field>,... -> (config, design, field)."""
    p = line.split("configuration_loaded=", 1)[1].split(",")
    return p[0], p[1], (p[2] if len(p) > 2 else "")


def robot_state(events, t0, dur_s):
    """
    Robot state at the start ``t0`` of an exposure lasting ``dur_s`` seconds.

    ``events`` is one night of jaeger lines from :func:`read_jaeger_extract`.
    The rule (``robots_not_moved``) fires when

    * the last ``configuration_loaded`` before ``t0`` happened less than
      ``MAX_LOAD_AGE_S`` before ``t0``;
    * no ``Starting trajectory`` happened between that load and ``t0``;
    * a trajectory did happen earlier that night, after a load of a different
      design: that load's configuration is where the robots are (A).
    """
    loads = [(t, *_load_fields(l), l, f) for t, l, f in events if "configuration_loaded=" in l]
    traj = [(t, f) for t, l, f in events if 'text="Starting trajectory' in l]
    fold = [t for t, l, f in events if "folded=T" in l]
    t1 = t0 + dt.timedelta(seconds=dur_s)

    before = [x for x in loads if x[0] <= t0]
    last_load = before[-1] if before else None
    last_traj = max((x for x in traj if x[0] <= t0), default=None, key=lambda x: x[0])
    moved_load = None
    if last_traj:
        pr = [x for x in loads if x[0] <= last_traj[0]]
        moved_load = pr[-1] if pr else None
    fires = bool(
        last_load
        and (last_traj is None or last_traj[0] < last_load[0])
        and moved_load
        and last_load[2] != moved_load[2]
        and (t0 - last_load[0]).total_seconds() < MAX_LOAD_AGE_S
    )
    last_fold = max((t for t in fold if t <= t0), default=None)
    folded = bool(last_fold and (last_traj is None or last_traj[0] <= last_fold))
    traj_during = [t for t, _ in traj if t0 < t < t1]
    return dict(
        robots_not_moved=fires,
        config_loaded=last_load[1] if last_load else "",
        design_loaded=last_load[2] if last_load else "",
        field_loaded=last_load[3] if last_load else "",
        load_time_ut=last_load[0].isoformat() if last_load else "",
        load_log_file=last_load[5] if last_load else "",
        config_at_last_move=moved_load[1] if moved_load else "",
        design_at_last_move=moved_load[2] if moved_load else "",
        field_at_last_move=moved_load[3] if moved_load else "",
        move_load_time_ut=moved_load[0].isoformat() if moved_load else "",
        last_trajectory_ut=last_traj[0].isoformat() if last_traj else "",
        minutes_since_load=round((t0 - last_load[0]).total_seconds() / 60, 1) if last_load else "",
        folded_at_start=folded,
        trajectory_during=bool(traj_during),
        trajectory_offset_s=round((traj_during[0] - t0).total_seconds()) if traj_during else "",
    )


def cmd_state(args):
    data = read_jaeger_extract(args.extract)
    out = []
    with open(args.exposures) as fp:
        for r in csv.DictReader(fp):
            key = (r["tele"], int(r["mjd"]))
            if key not in data:
                continue
            t0 = dt.datetime.fromisoformat(r["t0_ut"])
            s = robot_state(data[key], t0, float(r["dur_s"]))
            if args.all or s["robots_not_moved"]:
                out.append(dict(tele=r["tele"], mjd=r["mjd"], expnum=r["expnum"], t0_ut=r["t0_ut"],
                                dur_s=r["dur_s"], hdr_config=r["hdr_config"], **s))
    _write_csv(args.out, out)
    print(f"{len(out)} exposures written to {args.out}", file=sys.stderr)


# --------------------------------------------------------------------------
# step 2: compare the APOGEE assignments of B and A
# --------------------------------------------------------------------------


def confsummary_path(root, tele, config):
    s = str(config)
    d = Path(root) / tele / "summary_files" / f"{s[:-3].zfill(3)}XXX" / f"{s[:-2].zfill(4)}XX"
    for flavour in ("FS", "S", "", "F"):  # the order almanac uses
        p = d / f"confSummary{flavour}-{config}.par"
        if p.exists():
            return p
    return None


def apogee_assignments(path):
    """{fiberId: catalogid} for assigned APOGEE fibers of a confSummary file."""
    cols, in_struct, out = [], False, {}
    with open(path, errors="replace") as fp:
        for line in fp:
            if line.startswith("typedef struct"):
                in_struct, cols = True, []
                continue
            if in_struct:
                if line.startswith("}"):
                    in_struct = False
                else:
                    m = re.match(r"\s*\w+\s+(\w+)", line)
                    if m:
                        cols.append(m.group(1))
                continue
            if line.startswith("FIBERMAP "):
                toks = re.findall(r'\{[^}]*\}|"[^"]*"|\S+', line)[1:]
                if len(toks) != len(cols):
                    continue
                d = dict(zip(cols, toks))
                if d.get("fiberType") == "APOGEE" and d.get("assigned") == "1":
                    out[int(d["fiberId"])] = d.get("catalogid")
    return out


def _keyed(path, cols):
    if not path:
        return {}
    with open(path) as fp:
        return {(r["tele"], int(r["mjd"]), int(r["expnum"])): {c: r.get(c, "") for c in cols} for r in csv.DictReader(fp)}


def cmd_cfgdiff(args):
    release = _keyed(args.release, ("eclass", "nrows"))
    checks = _keyed(args.data_check, ("group", "verdict", "verdict_note"))
    cache = {}

    def amap(tele, cfg):
        if (tele, cfg) not in cache:
            p = confsummary_path(args.sdsscore, tele, cfg)
            cache[(tele, cfg)] = (apogee_assignments(p), p.name) if p else None
        return cache[(tele, cfg)]

    out = []
    with open(args.state) as fp:
        for r in csv.DictReader(fp):
            if r["robots_not_moved"] != "True":
                continue
            b, a = amap(r["tele"], r["hdr_config"]), amap(r["tele"], r["config_at_last_move"])
            if not (a and b):
                n_diff = ""
            else:
                fibers = set(a[0]) | set(b[0])
                n_diff = sum(1 for f in fibers if a[0].get(f) != b[0].get(f))
            k = (r["tele"], int(r["mjd"]), int(r["expnum"]))
            rel = release.get(k)
            chk = checks.get(k, {})
            o = dict(r)
            o.update(
                n_apogee_fibers_target_differs=n_diff,
                confsummary_B=b[1] if b else "missing",
                confsummary_A=a[1] if a else "missing",
                in_release_040=bool(rel),
                eclass_040=rel["eclass"] if rel else "",
                data_check=chk.get("verdict", "NOT_TESTED") or "NOT_TESTED",
                data_check_group=chk.get("group", ""),
                data_check_note=chk.get("verdict_note", ""),
            )
            out.append(o)
    if args.differing_only:
        out = [o for o in out if o["n_apogee_fibers_target_differs"] not in ("", 0)]
    _write_csv(args.out, out)
    print(f"{len(out)} exposures written to {args.out}", file=sys.stderr)


# --------------------------------------------------------------------------
# step 3: selection, list CSV and override entries
# --------------------------------------------------------------------------


def exclusion(r):
    """Why a candidate is not listed ('' if it is listed)."""
    if r["n_apogee_fibers_target_differs"] in ("", "0"):
        return "same APOGEE targets in A and B (harmless)"
    if r["tele"] == "lco" and int(r["mjd"]) < LCO_FIRST_RELIABLE_MJD:
        return f"LCO before MJD {LCO_FIRST_RELIABLE_MJD}: header/log clocks disagree, signature unreliable"
    if r["data_check"] == "MATCHES_B":
        return "fiber-level data check shows the light follows the recorded configuration B"
    return ""


def read_candidates(path=CANDIDATES):
    with open(path) as fp:
        return list(csv.DictReader(fp))


def select(rows):
    listed, excluded = [], []
    for r in rows:
        why = exclusion(r)
        (excluded if why else listed).append((r, why))
    return [r for r, _ in listed], excluded


#: Why the fiber-level data check (2026-11-19, FIBER_CHECK.md) left these
#: exposures undetermined; quoted into the entries' reasons.
UNDETERMINED_NOTES = {
    ("apo", "60114", "53"): "Spearman rho_A 0.37 vs rho_B -0.01, too weak to call; 4-read frame; "
                            "in the hal log the expose command came about 15 s before the load",
    ("apo", "60844", "27"): "Spearman statistics point to A (rho_A 0.74 vs rho_B 0.08) but bright sky defeats the lit/unlit check",
    ("lco", "60941", "15"): "Spearman statistics point to A (rho_A 0.88 vs rho_B 0.02) but bright sky defeats the lit/unlit check",
    ("lco", "60481", "49"): "Spearman statistics point to A (rho_A 0.85 vs rho_B 0.03) but bright sky defeats the lit/unlit check",
}


def _ranges(nums):
    nums = sorted(nums)
    out, start, prev = [], nums[0], nums[0]
    for n in nums[1:] + [None]:
        if n is not None and n == prev + 1:
            prev = n
            continue
        out.append(str(start) if start == prev else f"{start}-{prev}")
        if n is not None:
            start = prev = n
    return ",".join(out)


def _check_phrase(r):
    v = r["data_check"]
    text = f"{r['expnum']} {v}"
    extra = []
    if v == "NOT_TESTED":
        if r["in_release_040"] == "True":
            extra.append(f"0.4.0 class {r['eclass_040']}")
        else:
            extra.append("not in the 0.4.0 release")
    elif (r["tele"], r["mjd"], r["expnum"]) in UNDETERMINED_NOTES:
        extra.append(UNDETERMINED_NOTES[(r["tele"], r["mjd"], r["expnum"])])
    elif r["data_check_note"]:
        extra.append(r["data_check_note"])
    return text + (f" ({'; '.join(extra)})" if extra else "")


def group_entries(listed):
    groups = collections.OrderedDict()
    for r in sorted(listed, key=lambda r: (r["tele"], int(r["mjd"]), int(r["expnum"]))):
        k = (r["tele"], int(r["mjd"]), r["config_at_last_move"], r["hdr_config"])
        groups.setdefault(k, []).append(r)
    entries = []
    for (tele, mjd, cfg_a, cfg_b), rs in groups.items():
        exps = [int(r["expnum"]) for r in rs]
        n_diff = rs[0]["n_apogee_fibers_target_differs"]
        verdicts = collections.Counter(r["data_check"] for r in rs)
        flags = []
        folded = [r["expnum"] for r in rs if r["folded_at_start"] == "True"]
        moving = [f"{r['expnum']} (+{r['trajectory_offset_s']} s)" for r in rs if r["trajectory_during"] == "True"]
        if folded:
            flags.append(
                f"The robots were also folded at the start of exposure(s) {', '.join(folded)} "
                f"(jaeger folded=T after the last trajectory), so those fibers were at neither configuration."
            )
        if moving:
            flags.append(
                f"A robot trajectory started during exposure(s) {', '.join(moving)}, so their light is mixed."
            )
        if any(v in ("UNKNOWN", "NOT_TESTED") for v in verdicts):
            flags.append(
                "Where the data check is undetermined or was not run, the exposure is listed on the log "
                "evidence alone: it is bad either way."
            )
        reason = (
            f"Robots not moved. Configuration {cfg_b} (B, recorded in the header) was loaded "
            f"{rs[0]['minutes_since_load']} min before exposure {exps[0]} started, but no robot trajectory ran "
            f"between that load and the exposure start(s), so the fibers were still at configuration {cfg_a} "
            f"(A, the configuration the robots were last moved to). {n_diff} APOGEE fibers have a different "
            f"target in A and B."
            + "".join(" " + f for f in flags)
            + " Fiber-level data check (2026-11-19; fiber light vs. catalog H of the A and B targets): "
            + "; ".join(_check_phrase(r) for r in rs)
            + "."
        )
        r0 = rs[0]
        lines = [f"{r0['load_time_ut']}Z configuration_loaded={r0['config_loaded']},{r0['design_loaded']},{r0['field_loaded']},..."]
        lines.append(
            "no 'Starting trajectory' before exposure start(s) "
            + ", ".join(f"{r['t0_ut']}Z" for r in rs)
        )
        lines.append(
            f"last 'Starting trajectory' {r0['last_trajectory_ut']}Z followed "
            f"{r0['move_load_time_ut']}Z configuration_loaded={r0['config_at_last_move']},{r0['design_at_last_move']},{r0['field_at_last_move']},..."
        )
        notes = (
            f"not_science for 0.4.1 (see the file header). Data check: "
            + ", ".join(f"{n} {v}" for v, n in sorted(verdicts.items()))
            + f". Candidate for a later use_config {cfg_a} (whole exposure) only where the data check says MATCHES_A."
        )
        entries.append(dict(
            id=f"{tele}-{mjd}-robots-not-moved-a{cfg_a}-b{cfg_b}",
            observatory=tele,
            mjd=mjd,
            exposures=_ranges(exps),
            action="not_science",
            recorded_config=int(cfg_b),
            actual_config=int(cfg_a),
            reason=reason,
            source=dict(
                file=f"tron jaeger actor log {r0['load_log_file']} ({tele}; Utah sdss51 sdsswork/data/logs/{tele}/tron/jaeger)",
                quote=" / ".join(lines),
            ),
            notes=notes,
        ))
    return entries


def _q(s):
    return json.dumps(s, ensure_ascii=False)


def render_block(entries):
    out = [BEGIN]
    for e in entries:
        out.append(f"  - id: {e['id']}")
        out.append(f"    observatory: {e['observatory']}")
        out.append(f"    mjd: {e['mjd']}")
        out.append(f"    exposures: {_q(e['exposures'])}")
        out.append(f"    action: {e['action']}")
        out.append(f"    recorded_config: {e['recorded_config']}")
        out.append(f"    actual_config: {e['actual_config']}")
        out.append("    reason: >-")
        out.extend("      " + l for l in textwrap.wrap(e["reason"], 96, break_long_words=False, break_on_hyphens=False))
        out.append("    source:")
        out.append(f"      file: {_q(e['source']['file'])}")
        out.append(f"      quote: {_q(e['source']['quote'])}")
        out.append(f"    notes: {_q(e['notes'])}")
    out.append(END)
    return "\n".join(out) + "\n"


def replace_block(text, block):
    lines = text.splitlines(keepends=True)
    try:
        i = next(n for n, l in enumerate(lines) if l.rstrip("\n") == BEGIN)
        j = next(n for n, l in enumerate(lines) if l.rstrip("\n") == END)
    except StopIteration:
        return text.rstrip("\n") + "\n" + block
    return "".join(lines[:i]) + block + "".join(lines[j + 1:])


def current_block(text):
    lines = text.splitlines(keepends=True)
    i = next(n for n, l in enumerate(lines) if l.rstrip("\n") == BEGIN)
    j = next(n for n, l in enumerate(lines) if l.rstrip("\n") == END)
    return "".join(lines[i:j + 1])


LIST_COLUMNS = [
    "tele", "mjd", "expnum", "t0_ut", "hdr_config", "config_at_last_move", "minutes_since_load",
    "n_apogee_fibers_target_differs", "folded_at_start", "trajectory_during", "in_release_040", "eclass_040",
    "data_check", "data_check_group", "data_check_note", "override_id",
]


def cmd_overrides(args):
    rows = read_candidates(args.candidates)
    listed, excluded = select(rows)
    entries = group_entries(listed)
    ids = {}
    for e in entries:
        for r in listed:
            if (r["tele"], int(r["mjd"]), r["config_at_last_move"], r["hdr_config"]) == (
                e["observatory"], e["mjd"], str(e["actual_config"]), str(e["recorded_config"])
            ):
                ids[(r["tele"], r["mjd"], r["expnum"])] = e["id"]
    if args.list_csv:
        _write_csv(args.list_csv, [
            {c: (ids[(r["tele"], r["mjd"], r["expnum"])] if c == "override_id" else r.get(c, "")) for c in LIST_COLUMNS}
            for r in listed
        ])
    block = render_block(entries)
    if args.write_yaml:
        path = Path(args.write_yaml)
        path.write_text(replace_block(path.read_text(), block))
    else:
        sys.stdout.write(block)
    by = collections.Counter(r["tele"] for r in listed)
    nights = collections.Counter(t for t, m in {(r["tele"], r["mjd"]) for r in listed})
    print(
        f"listed {len(listed)} exposures ({dict(by)}) on {dict(nights)} nights in {len(entries)} entries; "
        f"excluded {len(excluded)}: " + "; ".join(f"{r['tele']} {r['mjd']}/{r['expnum']}: {w}" for r, w in excluded),
        file=sys.stderr,
    )


def _write_csv(path, rows):
    if not rows:
        Path(path).write_text("")
        return
    with open(path, "w", newline="") as fp:
        w = csv.DictWriter(fp, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("state", help="robot state at exposure start from jaeger log extracts")
    s.add_argument("--extract", nargs="+", required=True, help="output(s) of remote_extract_jaeger.sh")
    s.add_argument("--exposures", required=True, help="CSV: tele,mjd,expnum,t0_ut (ISO, UT),dur_s,hdr_config")
    s.add_argument("--all", action="store_true", help="write every exposure, not only those where the rule fires")
    s.add_argument("--out", required=True)
    s.set_defaults(func=cmd_state)

    c = sub.add_parser("cfgdiff", help="compare APOGEE assignments of B and A; build the candidate table")
    c.add_argument("--state", required=True, help="output of `state`")
    c.add_argument("--sdsscore", required=True, help="sdsscore root holding <obs>/summary_files/")
    c.add_argument("--release", help="CSV tele,mjd,expnum,eclass,nrows of the released exposures (optional)")
    c.add_argument("--data-check", help="CSV tele,mjd,expnum,group,verdict,verdict_note (optional)")
    c.add_argument("--differing-only", action="store_true", help="drop exposures whose A and B targets agree")
    c.add_argument("--out", default=str(CANDIDATES))
    c.set_defaults(func=cmd_cfgdiff)

    o = sub.add_parser("overrides", help="write the list CSV and the generated block of exposure_overrides.yaml")
    o.add_argument("--candidates", default=str(CANDIDATES))
    o.add_argument("--list-csv", help="write the listed exposures here")
    o.add_argument("--write-yaml", nargs="?", const=str(OVERRIDES_YAML),
                   help="replace the generated block in this override file (default: the packaged one)")
    o.set_defaults(func=cmd_overrides)

    args = p.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
