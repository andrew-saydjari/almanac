#!/usr/bin/env python
"""
Generate the ``handplaced-2011`` block of ``src/almanac/etc/exposure_overrides.yaml``
from ``handplaced_2011.csv`` (one row per exposure; see README.md).

Rows with ``action`` = ``retarget_fibers`` become one entry per (MJD, target,
fiber): the fiber saw the named star (its targeting information is in
``handplaced_targets.yaml``) and, because the telescope was pointed at the
star rather than at the plate field, every other fiber is ``offtarget``.
Rows with ``action`` = ``not_science`` become one entry per (MJD, target):
the telescope was pointed off the plate field, but the fiber that saw the
star is not established (no star light detected, or two fibers lit, or the
star's identity is in doubt), so the exposure is marked bad. ``skip`` rows
are not written (the reason is in their ``note``).

Usage::

    python scripts/handplaced_targets/make_overrides.py              # print the block
    python scripts/handplaced_targets/make_overrides.py --write-yaml # replace it in the YAML
"""

import argparse
import csv
import re
import sys
from collections import OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
CSV = HERE / "handplaced_2011.csv"
OVERRIDES_YAML = REPO / "src" / "almanac" / "etc" / "exposure_overrides.yaml"
BEGIN = "  # BEGIN handplaced-2011 (generated by scripts/handplaced_targets/make_overrides.py; do not edit by hand)"
END = "  # END handplaced-2011"
INSERT_BEFORE = "  # BEGIN robots-not-moved"


def read_rows(path=CSV):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def slug(name):
    return re.sub(r"[^a-z0-9]+", "", name.lower().replace("+", "p"))


def spans(numbers):
    numbers = sorted(numbers)
    out, start, prev = [], numbers[0], numbers[0]
    for n in numbers[1:]:
        if n == prev + 1:
            prev = n
            continue
        out.append((start, prev))
        start = prev = n
    out.append((start, prev))
    return ",".join(f"{a}" if a == b else f"{a}-{b}" for a, b in out)


def _q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def group_entries(rows):
    groups = OrderedDict()
    for r in rows:
        if r["action"] == "skip":
            continue
        mjd = int(r["mjd"])
        if r["action"] == "retarget_fibers":
            key = (mjd, r["target"], int(r["fiber"]), "retarget_fibers")
        elif r["action"] == "not_science":
            key = (mjd, r["target"], 0, "not_science")
        else:
            raise ValueError(f"unknown action {r['action']!r}")
        groups.setdefault(key, []).append(r)
    return sorted(groups.items(), key=lambda kv: (kv[0][0], int(kv[1][0]["exposure"]), kv[0][3]))


def _range(values, fmt="{:.1f}"):
    v = sorted(float(x) for x in values if x not in ("", "nan"))
    if not v:
        return "n/a"
    a, b = fmt.format(v[0]), fmt.format(v[-1])
    return a if a == b else f"{a}-{b}"


def render_entry(key, rows):
    mjd, target, fiber, action = key
    exps = [int(r["exposure"]) for r in rows]
    plates = sorted({r["plate"] for r in rows})
    sep_star = _range([r["sep_hdr_star_arcsec"] for r in rows])
    sep_plate = _range([r["sep_hdr_plate_centre_deg"] for r in rows], "{:.0f}")
    sources = sorted({r["fiber_source"] for r in rows})
    quote = " / ".join(dict.fromkeys(r["log_lines"] for r in rows if r["log_lines"]))
    notes = list(dict.fromkeys(r["note"] for r in rows if r["note"]))
    pointing = (
        f"Hand-placed-star commissioning test with plate {', '.join(plates)} plugged: the raw-header "
        f"RA/DEC is {sep_star} arcsec from {target} (J2000 + proper motion to 2011.5) and {sep_plate} deg "
        f"from the plate's targets, so no plugged fiber saw its plugmap target."
    )
    if action == "retarget_fibers":
        eid = f"apo-{mjd}-handplaced-{slug(target)}-f{fiber}"
        snr = _range([r["data_snr_mad"] for r in rows], "{:.0f}")
        src = {
            ("log",): "the observers' log",
            ("log-inherit",): "the observers' log, carried from the previous line",
            ("log", "log-inherit"): "the observers' log, for some exposures carried from the previous line",
            ("header",): "the raw-header OBSCMNT only",
            ("header", "log"): "the observers' log, and for some exposures the raw-header OBSCMNT only",
            ("header", "log-inherit"): "the observers' log carried from the previous line, or the raw-header OBSCMNT",
            ("header", "log", "log-inherit"): "the observers' log (some carried from the previous line) or the raw-header OBSCMNT",
        }[tuple(sources)]
        reason = (
            f"{pointing} {target} fell on fiber {fiber} (fiber from {src}). "
            f"Data check (raw up-the-ramp signal, chip b, flat-calibrated trace numbering): fiber {fiber} "
            f"is the brightest trace in every listed exposure (S/N {snr} in MAD units)."
        )
        lines = [
            f"  - id: {eid}",
            "    observatory: apo",
            f"    mjd: {mjd}",
            f"    exposures: {_q(spans(exps))}",
            "    action: retarget_fibers",
            f"    fibers: {{{fiber}: {_q(target)}}}",
            "    other_fibers: offtarget",
        ]
    else:
        eid = f"apo-{mjd}-handplaced-{slug(target)}-unconfirmed"
        reason = (
            f"{pointing} The fiber that saw {target} is not established for these exposures, so they "
            f"are not usable: " + "; ".join(f"{r['exposure']}: {r['note']}" for r in rows) + "."
        )
        notes = []
        lines = [
            f"  - id: {eid}",
            "    observatory: apo",
            f"    mjd: {mjd}",
            f"    exposures: {_q(spans(exps))}",
            "    action: not_science",
        ]
    lines.append(f"    reason: {_q(reason)}")
    if notes:
        lines.append(f"    notes: {_q(' '.join(n[0].upper() + n[1:] + ('' if n.endswith('.') else '.') for n in notes))}")
    lines += [
        "    source:",
        f"      file: raw/APOGEE/apo/{mjd}/{mjd}.comments",
        f"      quote: {_q(quote or 'raw-header OBSCMNT: ' + rows[0]['hdr_obscmnt'])}",
    ]
    return lines


def render_block(entries):
    out = [BEGIN]
    for key, rows in entries:
        out += render_entry(key, rows)
    out.append(END)
    return "\n".join(out) + "\n"


def current_block(text):
    lines = text.splitlines(keepends=True)
    try:
        i = next(n for n, l in enumerate(lines) if l.rstrip("\n") == BEGIN)
        j = next(n for n, l in enumerate(lines) if l.rstrip("\n") == END)
    except StopIteration:
        return None
    return "".join(lines[i:j + 1])


def write_yaml(block, path=OVERRIDES_YAML):
    text = path.read_text()
    old = current_block(text)
    if old is not None:
        text = text.replace(old, block)
    else:
        i = text.index(INSERT_BEFORE)
        text = text[:i] + block + text[i:]
    path.write_text(text)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--write-yaml", action="store_true")
    a = p.parse_args()
    block = render_block(group_entries(read_rows()))
    if a.write_yaml:
        write_yaml(block)
        print(f"wrote {OVERRIDES_YAML}", file=sys.stderr)
    else:
        sys.stdout.write(block)


if __name__ == "__main__":
    main()
